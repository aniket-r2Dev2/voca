const { test, expect } = require('@playwright/test');
const original = '- Built services for 20 users.\n- Maintained identity APIs.\n- Wrote unit tests.';
async function prepare(page) {
  await page.goto('./#/tailor');
  await page.getByLabel('Paste text or open a TXT, DOCX or PDF file').check();
  await page.getByLabel('Resume text').fill('Name: Alex\nEmail: private@example.com\nSummary\nBuilds software.\nExperience\nEngineer | Original Co\n' + original);
  await page.getByLabel('Job description').fill('Build reliable identity services and tests.');
  await page.getByLabel('Role (optional)').fill('Platform engineer');
  await page.getByRole('button', { name: 'Review draft' }).click();
  const section = page.getByRole('region', { name: 'Experience bullet tailoring' });
  const checks = section.getByRole('checkbox');
  await expect(checks).toHaveCount(3);
  await checks.nth(0).check(); await checks.nth(1).check(); await checks.nth(2).check();
  await section.getByRole('button', { name: 'Prepare experience prompt' }).click();
  const prompt = await page.getByLabel('Experience prompt to share').inputValue();
  expect(prompt).not.toContain('private@example.com'); expect(prompt).not.toContain('Original Co');
  // The instructions contain a JSON schema example; the payload is the last paragraph.
  const payload = JSON.parse(prompt.split('\n\n').at(-1));
  const proposed = ['- Developed services for 20 users.', '- Supported identity APIs.', '- Authored unit tests.'];
  return { section, response: { requestId: payload.requestId, suggestions: payload.bullets.map((item, index) => ({ targetId: item.targetId, proposed: proposed[index], reason: 'Relevant to the job.', evidence: item.evidence })) } };
}
test('experience suggestions are individually reviewed, saved, reopened and exported without source changes', async ({ page }) => {
  const { section, response } = await prepare(page);
  await page.getByLabel('Experience AI JSON response').fill(JSON.stringify(response));
  await section.getByRole('button', { name: 'Review experience response' }).click();
  const cards = section.getByRole('article');
  await expect(cards).toHaveCount(3);
  const preview = page.locator('details').filter({ has: page.getByText('Resume preview', { exact: true }) });
  await expect(preview).toContainText('Built services for 20 users.');
  await expect(preview).not.toContainText('Developed services');
  await page.getByRole('button', { name: 'Save draft' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Platform engineer' }).click();
  await expect(section.getByRole('button', { name: 'Accept bullet' })).toHaveCount(3);
  await cards.nth(0).getByRole('button', { name: 'Accept bullet' }).click();
  await cards.nth(1).getByRole('button', { name: 'Edit bullet', exact: true }).click();
  await cards.nth(1).getByLabel('Your bullet wording').fill('- Maintained secure identity APIs.');
  await cards.nth(1).getByRole('button', { name: 'Apply bullet wording' }).click();
  await cards.nth(2).getByRole('button', { name: 'Reject bullet' }).click();
  await page.getByRole('button', { name: 'Save draft' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Platform engineer' }).click();
  await expect(cards.nth(0)).toContainText('Decision: accepted');
  await expect(cards.nth(1)).toContainText('Decision: edited');
  await expect(cards.nth(2)).toContainText('Decision: rejected');
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('voca_career_profile_v1')));
  expect(saved.experiences).toEqual([]);
  expect(saved.tailorDrafts[0].source.experiences[0].description).toBe(original);
  expect(saved.tailorDrafts[0].source.experiences[0].company).toBe('Original Co');
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download draft PDF' }).click();
  const path = await (await pending).path();
  const text = require('child_process').execFileSync('pdftotext', [path, '-'], { encoding: 'utf8' });
  expect(text).toContain('Developed services for 20 users.');
  expect(text).toContain('Maintained secure identity APIs.');
  expect(text).toContain('Wrote unit tests.');
  expect(text).not.toContain('Authored unit tests.');
  expect(text).not.toContain('Built services for 20 users.');
});
test('invalid numeric claims and stale experience responses cannot change a draft', async ({ page }) => {
  const { section, response } = await prepare(page);
  response.suggestions[0].proposed = '- Developed services for 200 users.';
  await page.getByLabel('Experience AI JSON response').fill(JSON.stringify(response));
  await section.getByRole('button', { name: 'Review experience response' }).click();
  await expect(section.getByRole('status')).toContainText('numerical claims');
  await expect(section.getByRole('article')).toHaveCount(0);
  await page.getByLabel('Edit draft summary').fill('My new summary.');
  await expect(section.getByRole('button', { name: 'Review experience response' })).toBeDisabled();
  await expect(section.getByText('This draft changed. Prepare a new experience prompt.')).toBeVisible();
});
